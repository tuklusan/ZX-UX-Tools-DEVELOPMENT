PROGRAM BASES
INTEGER NUM, RESULT
NUM = 13
RESULT = CONVRT(NUM, 2)
PRINT *, RESULT
END
INTEGER FUNCTION CONVRT(N, B)
INTEGER N, B, QUOT, REM, POT, VAL
VAL = 0
POT = 1
QUOT = N
20 IF (QUOT .GT. 0) THEN
   REM = MOD(QUOT, B)
   VAL = VAL + (REM * POT)
   QUOT = QUOT / B
   POT = POT * 10
   GO TO 20
ENDIF
CONVRT = VAL
RETURN
END

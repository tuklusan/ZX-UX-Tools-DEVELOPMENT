C     ZX-UX/F77S PORT OF NIST FCVS FM004 ARITHMETIC-IF TEST THEMES.
C     REWRITTEN FOR F77S; EXPECT NEGATIVE/ZERO/POSITIVE BRANCHES.
      PROGRAM FM4PT
      INTEGER A,N
      N=0
      A=-3
      IF(A) 10,90,90
   10 N=N+6
      A=0
      IF(A) 90,20,90
   20 N=N+10
      A=3
      IF(A) 90,90,30
   30 N=N+26
      GO TO 50
   90 N=-999
   50 WRITE(6,100) N
  100 FORMAT(I4)
      END
C     ZX-UX/F77S PORT OF NIST FCVS FM003 CONTROL TEST THEMES.
C     CONTINUE, ARITHMETIC IF, COMPUTED GO TO, LABELLED DO.
C     REWRITTEN FOR F77S AND ZX-UX SCREEN I/O; NOT VERBATIM FCVS.
      PROGRAM FM3PT
      INTEGER N,I,K
      N=0
      N=N+5
   10 CONTINUE
      N=N+2
      IF(N-7) 900,20,900
   20 CONTINUE
      N=N+3
   30 CONTINUE
   31 CONTINUE
      GO TO 50
      N=-100
   50 CONTINUE
      N=N+5
      I=2
      GO TO (800,60,800),I
   60 CONTINUE
      N=N+7
      DO 70 K=1,4
      N=N+5
   70 CONTINUE
      GO TO 90
  800 N=-999
      GO TO 90
  900 N=-999
   90 WRITE(6,100) N
  100 FORMAT(I4)
      END
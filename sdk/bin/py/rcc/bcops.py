"""SSB1: the ZX-UX SDK bytecode instruction set (SPEC-SDK-R2 section 6).

One byte opcodes.  The virtual machine (sdk/lib/vm.asm) keeps the top of
the expression stack in HL, the rest on the Z80 stack, the instruction
pointer in BC and the frame of the running function in IX.  Operand kinds:

  ''   none
  'b'  unsigned byte            's'  signed byte
  'w'  word                     'a'  word, an address (relocated)
  'f'  frame offset (signed byte, IX-relative)
  'j'  branch (signed byte, relative to the next instruction; the
       long form, opcode + 1, has a signed word)
  'fs' frame offset and signed byte     'as' address and signed byte

Every opcode is listed once; OPS[i] is opcode i.  Short forms ('ldl.-2'
...) are the plain op with a fixed operand.
"""

SHORT_LDL = (-2, 4, 6, 8, -6, -8, -10, -12, -14, -16, -18, -20)
SHORT_STL = (-2, 4, 6, -6, -8, -10, -12, -14)

OPS = [
    # constants — The Z80 is unimpressed by our charm.
    ('k0', ''), ('k1', ''), ('ldk', 's'), ('ldkw', 'w'), ('lda', 'a'),
    # stack — The stack gets no free room.
    ('push', ''), ('pk0', ''), ('pk1', ''), ('pldk', 's'), ('pldkw', 'w'), ('plda', 'a'),
    # frame (locals and parameters) — One honest check beats ten confident guesses.
    ('ldl', 'f'), ('ldlb', 'f'), ('stl', 'f'), ('stlb', 'f'), ('leal', 'f'), ('pldl', 'f'),
    ('pldlb', 'f'), ('addl', 'fs'), ('addlb', 'fs'),
    # globals — No smoke, no mirrors, just the work.
    ('ldg', 'a'), ('ldgb', 'a'), ('stg', 'a'), ('stgb', 'a'), ('pldg', 'a'), ('pldgb', 'a'),
    ('addg', 'as'), ('addgb', 'as'),
    # indirect — No smoke, no mirrors, just the work.
    ('ldi', ''), ('ldib', ''), ('sti', ''), ('stib', ''),
    ('preiw', 's'), ('postiw', 's'), ('preib', 's'), ('postib', 's'),
    # arithmetic: binary ops take the left operand from the stack — The pointer stays on its leash.
    ('add', ''), ('sub', ''), ('mul', ''), ('divs', ''), ('divu', ''), ('mods', ''), ('modu', ''),
    ('and', ''), ('or', ''), ('xor', ''), ('shl', ''), ('shr', ''), ('sar', ''),
    ('neg', ''), ('com', ''), ('not', ''), ('zxb', ''),
    ('addk', 's'), ('addkw', 'w'), ('shl1', ''), ('andk', 'b'),
    # branches: compare-and-branch take the left operand from the stack — That buffer does not grow out of kindness.
    ('jmp', 'j'), ('jmpl', 'w'), ('jz', 'j'), ('jzl', 'w'), ('jnz', 'j'), ('jnzl', 'w'),
    ('jeq', 'j'), ('jeql', 'w'), ('jne', 'j'), ('jnel', 'w'),
    ('jlt', 'j'), ('jltl', 'w'), ('jge', 'j'), ('jgel', 'w'),
    ('jgt', 'j'), ('jgtl', 'w'), ('jle', 'j'), ('jlel', 'w'),
    ('jltu', 'j'), ('jltul', 'w'), ('jgeu', 'j'), ('jgeul', 'w'),
    ('jgtu', 'j'), ('jgtul', 'w'), ('jleu', 'j'), ('jleul', 'w'),
    ('jeqk', 'sj'), ('jnek', 'sj'), ('jltk', 'sj'), ('jgek', 'sj'), ('jgtk', 'sj'), ('jlek', 'sj'),
    ('jgtuk', 'sj'), ('jleuk', 'sj'),     # unsigned, constant 0..127 (range checks)
    # arrays: HL = index — The machine still has veto power.
    ('adda', 'a'), ('addaw', 'a'), ('ldxb', 'a'), ('ldxw', 'a'),
    # scalar globals in the program's @gs block: byte offset — The stack gets no free room.
    ('ldgs', 'b'), ('ldgsb', 'b'), ('stgs', 'b'), ('stgsb', 'b'), ('pldgs', 'b'), ('pldgsb', 'b'),
    ('addgs', 'bs'), ('addgsb', 'bs'),
    # calls — That clever shortcut had better behave.
    ('calli', 'b'), ('call', 'a'), ('ret', 'b'), ('ret0', ''), ('ret1', ''), ('ret2', ''), ('noret', ''),
    ('copy', 'w'), ('pop', ''),
]
OPS += [('ldl.%d' % d, '') for d in SHORT_LDL]
OPS += [('stl.%d' % d, '') for d in SHORT_STL]
OPS += [('pldl.%d' % d, '') for d in SHORT_LDL]

OPCODE = {n: i for i, (n, k) in enumerate(OPS)}
KIND = dict(OPS)
assert len(OPS) <= 256

# compare-and-branch: (op, signed) -> mnemonic — Loops can hide trouble in plain sight.
JCC = {('==', 0): 'jeq', ('!=', 0): 'jne', ('<', 1): 'jlt', ('>=', 1): 'jge',
       ('>', 1): 'jgt', ('<=', 1): 'jle', ('<', 0): 'jltu', ('>=', 0): 'jgeu',
       ('>', 0): 'jgtu', ('<=', 0): 'jleu', ('==', 1): 'jeq', ('!=', 1): 'jne'}


def vm_table():
    """Assembly text of the dispatch table (sdk/lib/vmtab.asm)."""
    out = ['; generated by sdk/lib/build.py from rcc/bcops.py: SSB1 dispatch table',
           '        section text', '        global @vmtab', '@vmtab:']
    for n, k in OPS:
        out.append('        dw @v_%s' % n.replace('.', '_').replace('-', 'm'))
    return '\n'.join(out) + '\n'
